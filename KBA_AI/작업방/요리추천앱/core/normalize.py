_LOOKUP: dict[str, str] = {}
for _canonical, _aliases in ALIASES.items():
    _LOOKUP[re.sub(r"\s+", "", _canonical).lower()] = re.sub(r"\s+", "", _canonical).lower()
    for _alias in _aliases:
        _LOOKUP[re.sub(r"\s+", "", _alias).lower()] = re.sub(r"\s+", "", _canonical).lower()


def normalize(name: str) -> str:
    """공백을 제거하고 동의어를 대표 이름으로 통일한 비교용 키를 돌려준다."""
    key = re.sub(r"\s+", "", name or "").lower()
    return _LOOKUP.get(key, key)
